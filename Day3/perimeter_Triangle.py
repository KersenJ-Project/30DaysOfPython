# Écrivez un script qui demande à l'utilisateur d'entrer le côté a, le côté b et le côté c d'un triangle. Calculez le périmètre du triangle

print("Ceci est un script pour calculer le perimetre d'un triangle.")

a = float(input("Entrer le cote a: "))
b = float(input("Entrer le cote b: "))
c = float(input("Entrer le cote c: "))

perimeter = a + b + c

print("Le perimetre du triangle est", perimeter)