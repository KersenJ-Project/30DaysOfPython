# Écrivez un script qui demande à l'utilisateur d'entrer la base et la hauteur d'un rectangle et calcule l'aire de ce rectangle

print("Ceci est un script pour calculer l'aire d'un rectangle.")

base = float(input("Entrer la base: "))
hauteur = float(input("Entrer la hauteur: "))

area_rectangle = base * hauteur

print("L'aire du rectangle est", area_rectangle)